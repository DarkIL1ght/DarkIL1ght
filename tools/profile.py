def svg(h, t, body, w=W):
    css = (f"text{{font-family:{SANS}}}.d{{font-family:{DISPLAY}}}.m{{font-family:{MONO}}}"
           "@keyframes b{50%{opacity:0}}.cur{animation:b 1.1s steps(1) infinite}"
           "@media (prefers-reduced-motion:reduce){.cur{animation:none}}")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">'
            f'<style>{css}</style>{body}</svg>\n')


def txt(x, y, s, size, fill, cls="", weight=400, extra=""):
    c = f' class="{cls}"' if cls else ""
    return (f'<text x="{x}" y="{y}"{c} font-size="{size}" font-weight="{weight}" fill="{fill}" {extra}>'
            f'{escape(s)}</text>')


def rule(y, t, x1=40, x2=W - 40):
    return f'<line x1="{x1}" y1="{y}" x2="{x2}" y2="{y}" stroke="{t["line"]}"/>'


def section(t, num, title, y=56):
    return (txt(40, y, f"{num:02d}", 13, t["mute"], "m") +
            txt(78, y, title, 34, t["fg"], "d", 900, 'letter-spacing="-1"') + rule(y + 22, t))


