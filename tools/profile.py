"""Generates the profile picture (assets/light|dark/header.svg) and README.md.

Style only, borrowed from the portfolio site: monochrome, a giant uppercase name,
mono captions in <brackets/>, the black-and-white portrait. Not a copy of the site:
details and case studies live there, the profile just points to them.

    python tools/profile.py

Edit the CONTENT block and re-run. The portrait is assets/photo.webp (embedded
into the SVG, because GitHub shows SVG files as images without outside requests).
"""

import base64
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://me.130-61-149-209.sslip.io/en/"

# ---------------------------------------------------------------- CONTENT ---
NAME = ("DARHAN", "SEMIYATOV")
ROLE = "GO BACKEND & AI ENGINEER"
META = "ALMATY, KZ  ·  GO @ QAZCODE / BEELINE  ·  OPEN TO ROLES FROM 2027"
# What I am building now: (project, one line). Details are on the portfolio site.
NOW = [
    ("Math-Lingo", "maths trainer for kids, live pilot"),
    ("Tropa", "places & meetups map, live"),
    ("IELTS scorer", "my own DeBERTa scoring model"),
    ("M094 Diploma", "team of 4, I lead the infra"),
]
LINKS = [
    ("Portfolio", SITE),
    ("LinkedIn", "https://www.linkedin.com/in/darhan-semiyatov-a5171b3a8"),
    ("Telegram", "https://t.me/DarkIL1ght"),
    ("Email", "mailto:semiatov@mail.ru"),
]

# ------------------------------------------------------------------ STYLE ---
# Transparent background: the picture sits on GitHub's own page colour, one set per theme.
THEMES = {
    "dark": dict(fg="#f2f2f2", mute="#8c8c8c", line="#30363d"),
    "light": dict(fg="#0a0a0a", mute="#6b6b6b", line="#d8dee4"),
}
DISPLAY = "'Arial Black','Helvetica Neue',Helvetica,Arial,sans-serif"
MONO = "SFMono-Regular,Consolas,'Liberation Mono',Menlo,monospace"
W, H = 1000, 430
PHOTO = dict(x=660, y=20, w=320, h=400)  # 408×510 source, same 4:5 ratio


def txt(x, y, s, size, fill, cls, weight=400, extra=""):
    return (f'<text x="{x}" y="{y}" class="{cls}" font-size="{size}" font-weight="{weight}" fill="{fill}" {extra}>'
            f'{escape(s)}</text>')


def header(t, photo):
    css = (f".d{{font-family:{DISPLAY}}}.m{{font-family:{MONO}}}"
           "@keyframes b{50%{opacity:0}}.cur{animation:b 1.1s steps(1) infinite}"
           "@media (prefers-reduced-motion:reduce){.cur{animation:none}}")
    p = PHOTO
    b = txt(20, 44, META, 12, t["mute"], "m", extra='letter-spacing="1"')
    b += txt(14, 148, NAME[0], 104, t["fg"], "d", 900, 'letter-spacing="-5"')
    b += txt(14, 244, NAME[1], 104, t["fg"], "d", 900, 'letter-spacing="-5" textLength="610" lengthAdjust="spacingAndGlyphs"')
    b += (f'<text x="20" y="290" class="m" font-size="19" fill="{t["mute"]}">&lt;'
          f'<tspan fill="{t["fg"]}">{escape(ROLE)}</tspan>/&gt;'
          f'<tspan class="cur" fill="{t["fg"]}">▍</tspan></text>')
    b += f'<line x1="20" y1="314" x2="620" y2="314" stroke="{t["line"]}"/>'
    for k, (name, line) in enumerate(NOW):
        y = 342 + k * 24
        b += txt(20, y, "→", 13, t["mute"], "m") + txt(44, y, name, 14, t["fg"], "m", 700)
        b += txt(190, y, line, 13, t["mute"], "m")
    b += (f'<image href="data:image/webp;base64,{photo}" x="{p["x"]}" y="{p["y"]}" width="{p["w"]}" height="{p["h"]}" '
          f'preserveAspectRatio="xMidYMid slice"/>')
    b += f'<rect x="{p["x"] + .5}" y="{p["y"] + .5}" width="{p["w"] - 1}" height="{p["h"] - 1}" fill="none" stroke="{t["line"]}"/>'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">'
            f'<title>{escape(" ".join(NAME))} — {escape(ROLE)}</title><style>{css}</style>{b}</svg>\n')


def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data, encoding="utf-8", newline="\n")


def readme():
    alt = f"{' '.join(NAME)}, {ROLE}. {META}. Now: " + "; ".join(f"{n} — {l}" for n, l in NOW)
    out = [
        f'<a href="{SITE}"><picture><source media="(prefers-color-scheme: dark)" srcset="assets/dark/header.svg"/>'
        f'<img src="assets/light/header.svg" alt="{escape(alt)}" width="100%"/></picture></a>',
        "",
        '<p align="center"><code>' + "</code> · <code>".join(f'<a href="{u}">{n}</a>' for n, u in LINKS) + "</code></p>",
        "",
        "<!-- generated by tools/profile.py -->",
        "",
    ]
    write(ROOT / "README.md", "\n".join(out))


def main():
    photo = base64.b64encode((ROOT / "assets" / "photo.webp").read_bytes()).decode()
    for mode, t in THEMES.items():
        d = ROOT / "assets" / mode
        for old in d.glob("*.svg"):
            old.unlink()
        write(d / "header.svg", header(t, photo))
    readme()


if __name__ == "__main__":
    main()
