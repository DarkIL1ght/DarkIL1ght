def card(t, i, p):
    slug, title, summary, metric, stack, status = p
    w, h = 480, 300
    label = {"live": "● LIVE", "code": "PUBLIC CODE", "case": "CASE STUDY"}[status]
    b = f'<rect x="0.5" y="0.5" width="{w - 1}" height="{h - 1}" fill="none" stroke="{t["line"]}"/>'
    # tab of a folder, like on the site
    b += f'<path d="M0.5 0.5h150l14 14" fill="none" stroke="{t["fg"]}" stroke-width="2"/>'
    b += txt(24, 48, f"{i:02d}", 12, t["mute"], "m")
    chip_w = 9 + len(label) * 7.6
    b += f'<rect x="{w - 24 - chip_w}" y="32" width="{chip_w}" height="22" fill="{t["chip"] if status == "live" else "none"}" stroke="{t["chip"]}"/>'
    b += txt(w - 24 - chip_w / 2, 47, label, 11, t["chipfg"] if status == "live" else t["fg"], "m", 700,
             'text-anchor="middle" letter-spacing="0.5"')
    b += txt(24, 96, title.upper(), 30 if len(title) < 16 else 25, t["fg"], "d", 900, 'letter-spacing="-1"')
    for k, line in enumerate(wrap(summary, 60)[:4]):
        b += txt(24, 128 + k * 21, line, 14.5, t["mute"])
    b += rule(222, t, 24, w - 24)
    b += txt(24, 252, metric, 19, t["fg"], "d", 900, 'letter-spacing="-0.3"')
    b += txt(24, 278, stack, 12, t["mute"], "m")
    return svg(h, t, b, w)


