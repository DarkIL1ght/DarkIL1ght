def write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data, encoding="utf-8", newline="\n")


def pic(name, alt, width="100%"):
    return (f'<picture><source media="(prefers-color-scheme: dark)" srcset="assets/dark/{name}.svg"/>'
            f'<img src="assets/light/{name}.svg" alt="{escape(alt)}" width="{width}"/></picture>')


def readme():
    out = [pic("header", f"{' '.join(NAME)} — {ROLE}. {META}"), ""]
    out += ['<p align="center">' + " · ".join(f'<a href="{u}">{n}</a>' for n, u in CONTACTS) + "</p>", ""]
    out += [pic("projects", "01 Selected work"), "", "<table>"]
    for r in range(0, len(PROJECTS), 2):
        out.append("<tr>")
        for i, p in enumerate(PROJECTS[r:r + 2], start=r + 1):
            slug, title, summary, metric = p[:4]
            url = f"{SITE}/en/projects/{slug}"
            more = f' · <a href="{CODE_URLS[slug]}">code</a>' if slug in CODE_URLS else ""
            out.append(f'<td width="50%"><a href="{url}">{pic(f"card-{slug}", f"{title}: {summary} {metric}")}</a>'
                       f'<br/><sub><a href="{url}">case study →</a>{more}</sub></td>')
        out.append("</tr>")
    out += ["</table>", "", pic("experience", "02 Experience: " + " ".join(EXPERIENCE[2])), "",
            pic("stack", "03 Stack: " + "; ".join(f"{g}: {s}" for g, s in STACK)), "",
            f'<a href="{SITE}/en/">{pic("footer", "Let us talk: portfolio, CV and case studies")}</a>', "",
            "<!-- generated by tools/profile.py -->", ""]
    write(ROOT / "README.md", "\n".join(out))


def main():
    for mode, t in THEMES.items():
        d = ROOT / "assets" / mode
        for old in d.glob("*.svg"):
            old.unlink()
        write(d / "header.svg", header(t))
        write(d / "projects.svg", projects_head(t))
        for i, p in enumerate(PROJECTS, start=1):
            write(d / f"card-{p[0]}.svg", card(t, i, p))
        write(d / "experience.svg", experience(t))
        write(d / "stack.svg", stack(t))
        write(d / "footer.svg", footer(t))
    readme()


if __name__ == "__main__":
    main()
